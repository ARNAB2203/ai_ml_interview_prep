"""LangGraph state machine with a bounded approval gate.

Run after installing `langgraph`:
    python examples/framework_demos/langgraph_approval_graph.py

The graph treats approval as state supplied by a trusted workflow—not as a
sentence generated by a model. That distinction is central to safe agent design.
"""

# %% Imports
from __future__ import annotations

from typing import Literal
from typing_extensions import TypedDict


class AgentState(TypedDict):
    request: str
    approval_granted: bool
    risk: str
    result: str
    trace: list[str]


def classify(state: AgentState) -> dict[str, object]:
    high_risk_verbs = ("delete", "deploy", "write", "send")
    risk = "high" if any(verb in state["request"].lower() for verb in high_risk_verbs) else "low"
    return {"risk": risk, "trace": [*state["trace"], f"classified:{risk}"]}


def route(state: AgentState) -> Literal["execute", "await_approval"]:
    return "execute" if state["risk"] == "low" or state["approval_granted"] else "await_approval"


def execute(state: AgentState) -> dict[str, object]:
    return {"result": f"executed bounded action: {state['request']}", "trace": [*state["trace"], "executed"]}


def await_approval(state: AgentState) -> dict[str, object]:
    return {"result": "approval required before side effect", "trace": [*state["trace"], "paused_for_approval"]}


def build_graph():
    from langgraph.graph import END, START, StateGraph

    graph = StateGraph(AgentState)
    graph.add_node("classify", classify)
    graph.add_node("execute", execute)
    graph.add_node("await_approval", await_approval)
    graph.add_edge(START, "classify")
    graph.add_conditional_edges(
        "classify",
        route,
        {"execute": "execute", "await_approval": "await_approval"},
    )
    graph.add_edge("execute", END)
    graph.add_edge("await_approval", END)
    return graph.compile()


def run_request(request: str, approval_granted: bool) -> AgentState:
    initial: AgentState = {
        "request": request,
        "approval_granted": approval_granted,
        "risk": "unknown",
        "result": "",
        "trace": [],
    }
    return build_graph().invoke(initial)


def demo() -> None:
    low_risk = run_request("summarize the approved runbook", approval_granted=False)
    blocked = run_request("deploy the new package", approval_granted=False)
    approved = run_request("deploy the new package", approval_granted=True)
    print("Low-risk run:", low_risk)
    print("Blocked high-risk run:", blocked)
    print("Approved high-risk run:", approved)
    assert low_risk["result"].startswith("executed")
    assert blocked["result"] == "approval required before side effect"
    assert approved["result"].startswith("executed")
    print("PASS: LangGraph routing and approval-gate checks completed.")


if __name__ == "__main__":
    demo()
